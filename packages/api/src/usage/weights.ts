/**
 * Quota weighting and unit resolution.
 *
 * These values are a BILLING construct and must never reach `Transaction`,
 * `tx.ts`, `tokenConfig`, or Langfuse — those record real provider cost and are
 * what the superadmin and provider invoices are reconciled against. The weight
 * exists only to make one aggregate quota honest across models whose cost per
 * token differs by orders of magnitude.
 */

export type UsageUnit = 'tokens' | 'images';

/** Applied when no rule matches. */
export const DEFAULT_USAGE_WEIGHT = 1;

/**
 * Endpoints the provider bills per image rather than per token. Counting their
 * tokens misprices them by ~20x, so they are metered in images instead.
 */
const IMAGE_ENDPOINTS: ReadonlySet<string> = new Set(['openrouter image', 'bdren ai image']);

/**
 * Endpoints where a model is reached directly rather than through an agent.
 * Measured cost per token: direct Claude $1.135/1M vs direct ChatGPT $0.549/1M
 * — a ratio of 2.07, so a 2x weight brings a Claude billing token within 4% of
 * every other billing token.
 */
const WEIGHTED_ENDPOINTS: ReadonlyMap<string, number> = new Map([['claude', 2]]);

function normalizeEndpoint(endpoint?: string | null): string {
  return String(endpoint ?? '')
    .trim()
    .toLowerCase();
}

/** Whether this endpoint is metered in images rather than tokens. */
export function unitFor(endpoint?: string | null): UsageUnit {
  return IMAGE_ENDPOINTS.has(normalizeEndpoint(endpoint)) ? 'images' : 'tokens';
}

/** Quota multiplier for raw token counts on this endpoint. */
export function weightFor(endpoint?: string | null): number {
  return WEIGHTED_ENDPOINTS.get(normalizeEndpoint(endpoint)) ?? DEFAULT_USAGE_WEIGHT;
}

/** Raw tokens converted to billing tokens, rounded up so a weight never loses usage. */
export function toBillingTokens(rawTokens: number, weight: number): number {
  return Math.ceil(Math.max(rawTokens, 0) * Math.max(weight, 0));
}

/**
 * Models whose provider bills per generated image rather than per token.
 *
 * Matched on the model id because that is the only identifier that survives into
 * `collectedUsage`, where an image generated by a delegated subagent has to be
 * recognised after the fact — the request that reserved quota was made on the
 * `agents` endpoint, before any subagent chose a model.
 *
 * Keep this list in step with the image models exposed in `librechat.yaml`; a
 * missed entry silently meters an image as ~4,175 tokens (~$0.001) instead of
 * one image (~$0.04).
 */
const IMAGE_MODEL_PATTERNS: readonly RegExp[] = [
  /grok-imagine/i,
  /gemini[\w.-]*-image/i,
  /qwen-image/i,
  /gpt-[\w.-]*-image/i,
  /seedream/i,
];

/** Whether usage on this model is billed per image. */
export function isImageModel(model?: string | null): boolean {
  const candidate = String(model ?? '').trim();
  if (candidate === '') {
    return false;
  }
  return IMAGE_MODEL_PATTERNS.some((pattern) => pattern.test(candidate));
}

interface ModelUsageRow {
  model?: string | null;
  output_tokens?: number | null;
  [key: string]: unknown;
}

/**
 * Splits one agent run's collected usage into the two meters.
 *
 * An image reaches the quota engine only at settlement: the reservation was made
 * on the `agents` endpoint before delegation happened, so it holds token
 * capacity and knows nothing about images. Partitioning here is what stops an
 * agent-generated image being metered as text.
 *
 * One usage row on an image model counts as one generation — the image
 * specialist is instructed to produce a single image per invocation, and the
 * provider reports a flat token count per generation regardless of resolution.
 */
export function splitImageUsage<T extends ModelUsageRow>(
  usages: ReadonlyArray<T | null | undefined> | undefined,
): { tokenUsages: T[]; images: number } {
  const tokenUsages: T[] = [];
  let images = 0;
  for (const usage of usages ?? []) {
    if (usage == null) {
      continue;
    }
    if (isImageModel(usage.model)) {
      /** A row that produced no output is a failed or refused generation; the
       *  provider does not bill it, so neither do we. */
      if (Number(usage.output_tokens ?? 0) > 0) {
        images += 1;
      }
      continue;
    }
    tokenUsages.push(usage);
  }
  return { tokenUsages, images };
}
